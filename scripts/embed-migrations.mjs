/**
 * Copies drizzle/*.sql into src/db/migrations.generated.ts so the server can migrate without the drizzle/
 * folder at runtime — Hostinger deploys only .next, node_modules and public. Same format as drizzle's
 * readMigrationFiles. Runs before every build and after `npm run db:generate`; tests check it is current.
 */
import crypto from "node:crypto";
import fs from "node:fs";

const journal = JSON.parse(fs.readFileSync("drizzle/meta/_journal.json", "utf8"));
const migrations = journal.entries.map((e) => {
  const query = fs.readFileSync(`drizzle/${e.tag}.sql`, "utf8");
  return { sql: query.split("--> statement-breakpoint"), bps: e.breakpoints, folderMillis: e.when, hash: crypto.createHash("sha256").update(query).digest("hex") };
});
const out = `// Generated by scripts/embed-migrations.mjs from drizzle/ — do not edit. Run \`npm run db:generate\` (or \`node scripts/embed-migrations.mjs\`).
export const MIGRATIONS: { sql: string[]; bps: boolean; folderMillis: number; hash: string }[] = ${JSON.stringify(migrations, null, 2)};
`;
fs.writeFileSync("src/db/migrations.generated.ts", out);
console.log(`✓ Embedded ${migrations.length} migrations in src/db/migrations.generated.ts`);
